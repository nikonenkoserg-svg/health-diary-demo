  // === RETRIEVAL: match user message to relevant topics ===
  getRelevantKnowledge(messages) {
    const lastMessages = messages.slice(-3).map(m => m.content.toLowerCase()).join(' ');
    const scores = {};

    // 1. Direct keyword match (weight 2)
    for (const [key, topic] of Object.entries(this.TOPICS)) {
      for (const kw of topic.keywords) {
        if (lastMessages.includes(kw)) {
          scores[key] = (scores[key] || 0) + 2;
        }
      }
    }

    // 2. Synonym match (weight 1)
    for (const [phrase, topicKeys] of Object.entries(this.SYNONYMS)) {
      if (lastMessages.includes(phrase)) {
        topicKeys.forEach(key => {
          if (this.TOPICS[key]) {
            scores[key] = (scores[key] || 0) + 1;
          }
        });
      }
    }

    // Sort by score, take top 2
    const sorted = Object.entries(scores)
      .sort((a, b) => b[1] - a[1])
      .slice(0, 2)
      .map(([key]) => ({ key, content: this.TOPICS[key].content }));

    // 3. Default fallback: if nothing matched, use body_reserve
    if (sorted.length === 0) {
      sorted.push({ key: 'body_reserve', content: this.TOPICS.body_reserve.content });
    }

    return sorted;
  },

  // === BUILD FULL SYSTEM PROMPT ===
  async buildPrompt(profile, userMsgCount, questionCount, messages) {
    let prompt = this.CORE_PROMPT;

    // RAG: подкладываем 3 ближайших карточки-эталона как примеры
    try {
      const lastUserMsg = (messages || []).slice().reverse().find(function(m){return m.role==='user';});
      if (lastUserMsg && typeof window !== 'undefined' && window.RAG && window.RAG.isReady()) {
        const hits = await window.RAG.search(lastUserMsg.content, 3);
        prompt += window.RAG.formatForPrompt(hits);
      }
    } catch (e) {
      console.warn('[RAG] search failed:', e);
    }

    // Add relevant knowledge (1 topic, truncated to ~400 chars)
    const knowledge = this.getRelevantKnowledge(messages || []);
    if (knowledge.length > 0) {
      prompt += '\nЗнания: ';
      knowledge.forEach(k => {
        const trimmed = k.content.length > 400 ? k.content.slice(0, 400) + '...' : k.content;
        prompt += trimmed;
      });
    }

    // Profile — через ProfileOrchestrator (этап 1: слой 1 + база слоя 2).
    // На запуске автоматическая миграция legacy профиля → ProfileStore v2.
    if (typeof ProfileStore !== 'undefined') {
      if (!ProfileStore._load() && profile && Object.keys(profile).length > 0) {
        ProfileStore.migrateFromLegacy(profile);
      }
      if (typeof ProfileOrchestrator !== 'undefined') {
        const lastUserMsg = (messages || []).slice().reverse().find(m => m.role === 'user');
        const msgType = lastUserMsg ? ProfileOrchestrator.classify(lastUserMsg.content) : 'other';
        const ctx = ProfileOrchestrator.contextFor(msgType);
        prompt += ProfileOrchestrator.formatForPrompt(ctx);

        // Жёсткий запрет на повторные вопросы по известным полям.
        const known = [];
        if (ProfileStore.get('anketa', 'sex')) known.push('пол');
        if (ProfileStore.get('anketa', 'age')) known.push('возраст');
        if (ProfileStore.get('anketa', 'weight')) known.push('вес');
        if (ProfileStore.get('anketa', 'height')) known.push('рост');
        if (known.length > 0) {
          prompt += `\nЭти параметры УЖЕ известны: ${known.join(', ')}. НЕ переспрашивай их. Уточнения допустимы только если пациент сам говорит про изменение.`;
        }
      }
    } else if (profile && Object.keys(profile).length > 0) {
      // Fallback на плоский профиль если ProfileStore не загружен
      prompt += '\n\nПрофиль: ';
      if (profile.sex) prompt += `${profile.sex}, `;
      if (profile.age) prompt += `${profile.age} лет, `;
      if (profile.weight) prompt += `${profile.weight} кг, `;
      if (profile.bmi) prompt += `ИМТ ${profile.bmi}, `;
      prompt = prompt.replace(/, $/, '');
    }

    // Phase-based tone
    if (userMsgCount <= 5)
      prompt += '\nФаза: начало. Спокойно, коротко, без лишних вопросов.';
    else if (userMsgCount <= 12)
      prompt += '\nФаза: знакомство. Можно быть живее.';
    else
      prompt += '\nФаза: доверие. Можно быть прямее и конкретнее.';

    if (questionCount >= 2)
      prompt += '\nТы уже задавал вопросы подряд — в этом ответе не задавай, дай комментарий.';

    // Информация о графике — пассивно. Прямые инструкции "скажи X" вызывают
    // дубль с уже построенным графиком и переспрос того что пациент уже сказал.
    prompt += `\n\n[О ГРАФИКЕ]
В верхней части экрана у пациента график глюкозы. Когда пациент пишет что ел или пил — график обновляется автоматически. Если в твоём промпте есть блок [ТЕКУЩЕЕ СОБЫТИЕ] — значит график уже построен, опирайся на его данные и НЕ дублируй их словами. Если блока [ТЕКУЩЕЕ СОБЫТИЕ] нет — значит пациент пока ничего не ел в этой сессии, не обещай график пока еды нет.
[/О ГРАФИКЕ]`;

    return prompt;
  }
