// Assistant — prompt, filter, profile parsing

const Assistant = {
  GREETING: `Здравствуйте, я ассистент дневника. Несколько слов о том, как это устроено.

Разговор у нас честный — я не притворяюсь врачом и не ставлю диагнозов. Я помогаю замечать то, что повторяется в вашем теле, связи, которые вы сами можете не видеть.

Никуда не тороплю. Общайтесь со мной как удобно — голосом, текстом, в любое время.

Чтобы я был полезен, расскажите, что привело. Недавний анализ? Тревога? Симптом, который не проходит? Или просто хочется разобраться, что происходит, пока ничего не болит?`,

  BASE_PROMPT: `Ты — ассистент дневника здоровья. Попутчик, не врач, не тренер, не приложение.

РОЛЬ:
- Помогаешь замечать закономерности в теле: связь еды, сна, стресса, движения с самочувствием и сахаром
- Ведёшь арифметику ресурса: каждый приём пищи, каждая ночь, каждая прогулка — нагрузка или разгрузка для поджелудочной
- Не ставишь диагнозов, не назначаешь лечение, не заменяешь врача
- Ты на стороне реальности: не подыгрываешь, не давишь советами

ТОН:
- Спокойный, тёплый, без восклицаний и пафоса
- Говори как умный знакомый, не как бот
- Короткие предложения, 1-3 за раз
- Не используй списки, маркеры, нумерацию
- Не используй markdown
- Без шаблонных фраз: "отличный вопрос", "рад помочь", "давай разберёмся"
- Можешь мягко подколоть, если уместно (после 5+ сообщений)

ЗНАНИЯ:
- Преддиабет: инсулинорезистентность, бета-клетки, гликированный гемоглобин
- Четыре опоры: сон, порядок еды, время еды, движение после еды
- Сон: одна ночь плохого сна = -25% чувствительности к инсулину, кортизол, мелатонин
- Порядок еды: белок и клетчатка первыми → пик сахара ниже в 1.5 раза
- Время еды: утром чувствительность к инсулину выше, вечером ниже
- Движение после еды: 2 минуты ходьбы = мышцы забирают сахар без инсулина
- Стресс: кортизол → печень выбрасывает сахар → сахар растёт без еды
- Микронагрузки: приседания, подъём на носки, планка, лестница — 15-60 сек, без инвентаря

ЕДА → НАГРУЗКА (для ~80 кг):
- 100г мороженого (~230 ккал) = 46 приседаний
- Эклер (~250 ккал) = 50 приседаний (5×10) ИЛИ 6 пролётов лестницы
- Кусок пиццы (~300 ккал) = 60 приседаний ИЛИ 8 пролётов
- Подача: "вот цена, раскидай по дню", НЕ наказание

ЖЕНСКОЕ ЗДОРОВЬЕ (если пол женский):
- Лютеиновая фаза: задержка воды, тяга к сладкому (прогестерон), низкая энергия
- Фолликулярная фаза: высокая энергия, лучше чувствительность к инсулину
- Щитовидка, дефицит железа, кортизол-стресс, влияние контрацептивов
- Вина за еду вреднее самой еды

ПЕРЕХВАТ ИНИЦИАТИВЫ:
- Пользователь несёт чушь → прямо: "Нет. [факт]"
- Пользователь паникует → "Стоп. Дыши."
- Пользователь ходит кругами → "Мы это уже обсудили"
- Пользователь готов действовать → без похвал, просто следующий шаг

ОГРАНИЧЕНИЯ:
- Максимум 5 предложений за ответ
- Не задавай больше одного вопроса за ответ
- Если уже задавал вопрос и не получил ответа — не повторяй
- Не предлагай "обратиться к врачу" в каждом сообщении — только когда реально нужно`,

  buildSystemPrompt(profile, userMsgCount, questionCount) {
    let prompt = this.BASE_PROMPT;

    // Add profile context
    if (profile && Object.keys(profile).length > 0) {
      prompt += '\n\nПРОФИЛЬ ПОЛЬЗОВАТЕЛЯ:\n';
      if (profile.sex) prompt += `Пол: ${profile.sex}\n`;
      if (profile.age) prompt += `Возраст: ${profile.age}\n`;
      if (profile.height) prompt += `Рост: ${profile.height} см\n`;
      if (profile.weight) prompt += `Вес: ${profile.weight} кг\n`;
      if (profile.bmi) prompt += `ИМТ: ${profile.bmi} (${profile.bmiCategory})\n`;
      if (profile.chronic && profile.chronic.length > 0)
        prompt += `Хронические: ${profile.chronic.join(', ')}\n`;
      if (profile.sleepHours) prompt += `Сон: ${profile.sleepHours} ч\n`;
      if (profile.stress) prompt += `Стресс: ${profile.stress}\n`;
    }

    // Phase-based tone
    if (userMsgCount <= 5)
      prompt += '\n\nФАЗА: начало. Говори спокойно, коротко. Не шути пока.';
    else if (userMsgCount <= 12)
      prompt += '\n\nФАЗА: знакомство. Можно мягко пошутить, если уместно.';
    else
      prompt += '\n\nФАЗА: доверие. Можно подколоть, быть прямее.';

    // Anti-question
    if (questionCount >= 1)
      prompt += '\nНе задавай вопросов в этом ответе.';

    return prompt;
  },

  // Parse profile from free text
  parseProfile(text) {
    const p = {};
    const t = text.toLowerCase();

    // Sex
    if (/\b(мужчина|мужской|муж|парень)\b/.test(t)) p.sex = 'мужской';
    else if (/\b(женщина|женский|жен|девушка)\b/.test(t)) p.sex = 'женский';
    else if (/\bм\b/.test(t) && /\d/.test(t)) p.sex = 'мужской';
    else if (/\bж\b/.test(t) && /\d/.test(t)) p.sex = 'женский';

    // Age
    const ageMatch = t.match(/(\d{1,2})\s*(лет|года|год)/);
    if (ageMatch) p.age = parseInt(ageMatch[1]);

    // Height
    const hMatch = t.match(/(\d{3})\s*(см|сантиметр)/);
    if (hMatch) p.height = parseInt(hMatch[1]);
    else {
      const hMatch2 = t.match(/рост\s*(\d{3})/);
      if (hMatch2) p.height = parseInt(hMatch2[1]);
    }

    // Weight
    const wMatch = t.match(/(\d{2,3})\s*(кг|килограмм)/);
    if (wMatch) p.weight = parseInt(wMatch[1]);
    else {
      const wMatch2 = t.match(/вес\s*(\d{2,3})/);
      if (wMatch2) p.weight = parseInt(wMatch2[1]);
    }

    // BMI
    if (p.height && p.weight) {
      const h = p.height / 100;
      p.bmi = (p.weight / (h * h)).toFixed(1);
      if (p.bmi < 18.5) p.bmiCategory = 'дефицит';
      else if (p.bmi < 25) p.bmiCategory = 'норма';
      else if (p.bmi < 30) p.bmiCategory = 'избыточный';
      else p.bmiCategory = 'ожирение';
    }

    // Chronic conditions
    p.chronic = [];
    if (/преддиабет|предиабет/.test(t)) p.chronic.push('преддиабет');
    if (/диабет(?!\s*нет)/.test(t) && !/преддиабет/.test(t)) p.chronic.push('диабет');
    if (/гипертон|давлени/.test(t)) p.chronic.push('гипертония');
    if (/аллерг/.test(t)) p.chronic.push('аллергия');

    return Object.keys(p).length > 0 ? p : null;
  },

  // Filter AI response
  filterResponse(text) {
    if (!text) return '';
    let r = text;

    // Remove markdown
    r = r.replace(/\*\*(.+?)\*\*/g, '$1');
    r = r.replace(/__(.+?)__/g, '$1');
    r = r.replace(/\*(.+?)\*/g, '$1');
    r = r.replace(/_(.+?)_/g, '$1');
    r = r.replace(/```[\s\S]*?```/g, '');
    r = r.replace(/`(.+?)`/g, '$1');

    // Remove lists
    r = r.replace(/^\s*[-•●◦▪]\s+/gm, '');
    r = r.replace(/^\s*\d+[.)]\s+/gm, '');

    // Remove URLs
    r = r.replace(/https?:\/\/\S+/g, '');

    // Remove template phrases (whole sentences)
    const templates = [
      /[^.!?]*спасибо за (честность|откровенность|доверие)[^.!?]*[.!?]/gi,
      /[^.!?]*точно подмечено[^.!?]*[.!?]/gi,
      /[^.!?]*интересный вопрос[^.!?]*[.!?]/gi,
      /[^.!?]*(молодец|горжусь|отличн)[^.!?]*[.!?]/gi,
      /[^.!?]*если (захочешь|хочешь) обсудить[^.!?]*[.!?]/gi,
      /[^.!?]*рад[а]? помочь[^.!?]*[.!?]/gi,
      /[^.!?]*обращайся[^.!?]*[.!?]/gi,
    ];
    templates.forEach(rx => { r = r.replace(rx, ''); });

    // Trim whitespace
    r = r.replace(/\n{3,}/g, '\n\n').trim();

    // Limit to 5 sentences
    const sentences = r.match(/[^.!?]+[.!?]+/g);
    if (sentences && sentences.length > 5) {
      r = sentences.slice(0, 5).join(' ').trim();
    }

    return r;
  }
};
