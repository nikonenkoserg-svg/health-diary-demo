// Onboarding — приветствие, заглушка до регистрации, тексты входа в анкету.

const Onboarding = {

  // === PRE-REGISTRATION GREETING ===
  GREETING: `Привет. Я — твой персональный ассистент по здоровью.

Я помогу тебе увидеть связи внутри организма — между сном, едой, нагрузками, настроением — и научиться ими управлять.

Ты можешь писать текстом, говорить голосом или отправить фото — как удобнее.

Чтобы начать — создай свой профиль. Это займёт пару минут, зато я сразу буду понимать твою ситуацию.`,

  // Единственная реплика-заглушка пока пациент не создал профиль.
  // До регистрации Спутник в диалог НЕ вступает — никаких ответов на вопросы,
  // никаких объяснений «что я умею». Это не сервис, это рабочее правило.
  PRE_REGISTER_HOLD: `Сначала создай профиль, дальше поговорим.`,

  // Скриптовые ответы (edge cases).
  RESPONSES: {
    aggressive: `Обдумай, если ещё не готов. Я никуда не тороплюсь.`
  },

  // Одна реплика входа после сохранения анкеты. Не вопрос — вход.
  ENTRY: `На связи. Напиши, что съел или о чём думаешь сейчас — начнём с этого.`,

  // Классификация коротких реплик пациента до регистрации.
  // Триггер регистрации больше НЕ текст — это кнопка «Создать профиль».
  // Здесь оставлено только распознавание агрессии.
  classifyResponse(text) {
    const t = (text || '').toLowerCase().trim();
    const aggro = /развод|впихив|подписк|разводка|бред|чушь|фигня|обман|нафиг|пошёл|пошел|отвали/;
    if (aggro.test(t)) return 'aggressive';
    return 'other';
  }
};

if (typeof window !== 'undefined') window.Onboarding = Onboarding;
